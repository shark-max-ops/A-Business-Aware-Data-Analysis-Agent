import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const directory = process.env.STAGE6E_DIR ? resolve(process.env.STAGE6E_DIR) : '';
test.skip(!directory, '需显式指定本机STAGE6E_DIR并启动6.E隔离前后端');
const read = (name: string) => JSON.parse(readFileSync(join(directory, name), 'utf8'));

test('real four-month source, retained quality and date controls on desktop and mobile', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const screenshots = join(directory, 'screenshots'); mkdirSync(screenshots, { recursive: true });
  await page.goto('/analysis');
  await expect(page.getByLabel('开始日期（含）', { exact: true })).toHaveValue('2026-01-01');
  await expect(page.getByLabel('结束日期（不含）', { exact: true })).toHaveValue('2026-05-01');
  await page.getByRole('button', { name: '工作区数据源 ↗' }).click();
  const drawer = page.getByRole('dialog', { name: '数据源与固定快照' });
  const summary = drawer.getByRole('region', { name: '快照覆盖与质量摘要' });
  await expect(summary).toContainText('计划时长：9');
  await expect(summary).toContainText('2026-04-30');
  await expect(summary).toContainText('612,102');
  await expect(summary).toContainText('2026-05-01');
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-source-desktop.png') });
  await drawer.getByRole('tab', { name: '来源清单', exact: true }).click();
  await expect(drawer.getByRole('tabpanel')).toContainText('2026-04.csv');
  await page.keyboard.press('Escape'); await expect(drawer).toBeHidden();
  await page.getByLabel('开始日期（含）', { exact: true }).fill('2026-02-14');
  await page.getByLabel('结束日期（不含）', { exact: true }).fill('2026-04-08');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-range-mobile.png') });
  await page.getByRole('button', { name: '新调查', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '新建调查', exact: true });
  await dialog.getByLabel('调查目标', { exact: true }).fill('6.E页面范围校验');
  await dialog.getByLabel('调查范围', { exact: true }).fill('只检查表单，不调用模型');
  await dialog.getByLabel('结束日期（不含）', { exact: true }).fill('2026-05-02');
  await expect(dialog).toContainText('日期范围超出所选快照覆盖');
  await expect(dialog.getByRole('button', { name: '固定范围并创建', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: /取\s*消/ }).click(); await expect(dialog).toBeHidden();
  await expect(page.locator('.analysis-status-bar').getByLabel('开始日期（含）', { exact: true })).toHaveValue('2026-02-14');
  expect(errors).toEqual([]);
});

test('actual model report, fixed old evidence and explicit narrow branch remain readable', async ({ page }) => {
  const names = ['monthly', 'followup', 'narrow'];
  test.skip(!names.every(name => existsSync(join(directory, `${name}.json`)) && read(`${name}.json`).passed), '真实模型案例须先独立核对通过');
  const cases = names.map(name => read(`${name}.json`));
  const first = cases[0], continued = cases[1], narrow = cases[2];
  const screenshots = join(directory, 'screenshots'); mkdirSync(screenshots, { recursive: true });
  await page.addInitScript(id => localStorage.setItem('analysis-conversation', id), first.run.conversation_id);
  await page.goto('/analysis');
  await expect(page.locator('.fixed-date-range')).toContainText(narrow.run.date_range.start);
  await page.getByRole('combobox', { name: '切换调查', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').getByText(read('investigation.json').goal, { exact: true }).click();
  await expect(page.locator('.fixed-date-range')).toContainText('2026-01-01 至 2026-05-01');
  const investigation = await (await page.request.get(`/api/v1/investigations/${first.run.investigation_id}`)).json();
  await expect(page.locator('.run-result')).toHaveCount(investigation.run_ids.length);
  const report = continued.report;
  await page.goto(`/reports/${report.report_id}/revisions/${report.revision_id}`);
  await expect(page.locator('.report-meta')).toContainText('2026-01-01 至 2026-05-01');
  const oldEvidence = continued.evidence.find((e: { artifact?: { run_id: string } }) => e.artifact && e.artifact.run_id !== continued.run.id);
  expect(oldEvidence).toBeTruthy();
  const block = report.blocks.find((b: { id: string }) => b.id === oldEvidence.block_id);
  if (block.type === 'kpi') await page.getByRole('button', { name: new RegExp(`^${block.title}：`) }).click();
  else if (block.type === 'text') await page.locator('.report-text button').filter({ hasText: oldEvidence.value.display }).first().click();
  else await page.locator('.report-block').filter({ has: page.getByRole('heading', { name: block.title, exact: true }) }).getByRole('button', { name: oldEvidence.value.display, exact: true }).first().click();
  const drawer = page.getByRole('dialog', { name: '这个结果从哪里来', exact: true });
  await expect(drawer).toContainText('引用旧轮次的证据');
  await expect(drawer).toContainText(oldEvidence.artifact.run_id);
  await expect(drawer).toContainText('2026-01-01 至 2026-05-01');
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-followup-evidence-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-followup-evidence-mobile.png') });
  await page.keyboard.press('Escape');
  await page.goto(`/reports/${narrow.report.report_id}/revisions/${narrow.report.revision_id}`);
  await expect(page.locator('.report-meta')).toContainText(`${narrow.run.date_range.start} 至 ${narrow.run.date_range.end_exclusive}`);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-narrow-report-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ animations: 'disabled', path: join(screenshots, 'real-narrow-report-desktop.png') });
});
