import { expect, test } from '@playwright/test';

test('isolated document, Chinese search, Wiki review/history, metric review and mobile', async ({ page, request }) => {
  const source = '# ArrDelay\n\nArrDelay is arrival time deviation. Early arrivals show negative numbers.\n\n| Field | Meaning |\n| --- | --- |\n| ArrDelay | Keep negative values for early arrivals |\n\n# Cancelled\n\nCancelled is a flight cancellation indicator.\n';
  const suffix = String(Date.now());
  const title = `合成浏览器验收材料-${suffix}`;
  await page.goto('/knowledge');
  await expect(page.getByRole('heading', { name: '为每个指标建立依据' })).toBeVisible();
  await page.getByLabel('原文文件', { exact: true }).setInputFiles({ name: 'synthetic-knowledge.md', mimeType: 'text/markdown', buffer: Buffer.from(source) });
  await page.getByLabel('文档标题', { exact: true }).fill(title);
  await page.getByRole('button', { name: '保存原文并索引' }).click();
  const row = page.getByRole('row').filter({ hasText: title });
  await expect(row.getByText('完成', { exact: true })).toBeVisible();
  await page.getByLabel('知识问题', { exact: true }).fill('提前到达为什么是负数');
  await page.getByRole('button', { name: '检索', exact: true }).click();
  await expect(page.locator('article.knowledge-hit').filter({ hasText: title }).first()).toBeVisible();
  await page.locator('article.knowledge-hit').filter({ hasText: title }).first().getByRole('button', { name: '选作 Wiki 引用' }).click();
  await row.getByRole('button', { name: '原文与历史' }).click();
  await expect(page.getByRole('combobox', { name: '原文历史版本', exact: true })).toBeVisible();
  await expect(page.locator('.ant-drawer').getByRole('cell', { name: 'Keep negative values for early arrivals', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');

  await page.getByRole('tab', { name: 'Wiki', exact: true }).click();
  await page.getByRole('button', { name: '新建 Wiki', exact: true }).click();
  await page.getByLabel('Wiki 页面标识', { exact: true }).fill(`browser-arrivals-${suffix}`);
  await page.getByLabel('Wiki 标题', { exact: true }).fill('提前到达的解释');
  await page.getByRole('button', { name: /插入所选原文及引用/ }).click();
  await page.getByRole('button', { name: '保存人工草稿', exact: true }).click();
  await expect(page.getByText('已保存为新草稿版本', { exact: true })).toBeVisible();
  await expect(page.getByRole('group', { name: '知识引用关系图', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '阅读解释', exact: true }).click();
  await expect(page.getByRole('button', { name: '查看引用 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '审核并发布', exact: true }).click();
  await page.getByRole('button', { name: '确认发布', exact: true }).click();
  await expect(page.getByText('已发布新版本', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '版本历史与回滚', exact: true }).click();
  const history = page.getByRole('dialog').filter({ hasText: 'Wiki 历史' });
  await expect(history.getByText('v2 · 已发布', { exact: true })).toBeVisible();
  await history.getByRole('button', { name: '以此版本新建草稿' }).last().click();
  await expect(page.getByText('已从历史创建新的回滚草稿，尚未发布')).toBeVisible();

  await page.getByRole('tab', { name: '指标定义', exact: true }).click();
  await page.getByRole('button', { name: '新建指标草稿' }).click();
  await page.getByLabel('指标键', { exact: true }).fill(`browser_test_rate_${suffix}`);
  await page.getByLabel('指标名称', { exact: true }).fill('合成验收指标');
  await page.getByLabel('指标粒度', { exact: true }).fill('carrier_id');
  await page.getByLabel('指标分子', { exact: true }).fill('合成符合条件记录数 × 100');
  await page.getByLabel('指标分母', { exact: true }).fill('合成全部记录数');
  await page.getByLabel('指标过滤', { exact: true }).fill('cancelled=0');
  await page.getByLabel('指标所需字段', { exact: true }).fill('cancelled');
  await page.getByLabel('指标空值规则', { exact: true }).fill('零分母返回 null');
  await page.getByRole('combobox', { name: '指标来源', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').getByText(`${title} v1`, { exact: true }).click();
  await page.getByRole('button', { name: '保存指标草稿' }).click();
  await expect(page.getByText('指标已保存为待审核新版本')).toBeVisible();
  await page.getByRole('button', { name: '审核此指标' }).click();
  await page.getByRole('button', { name: '确认审核', exact: true }).click();
  await expect(page.getByText('已创建已审核指标修订', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: '更新知识快照' }).click();
  await page.getByRole('button', { name: '检查所选日期适用性' }).click();
  await expect(page.getByText('当前快照与日期适用：合成验收指标 v2')).toBeVisible();
  await page.getByLabel('知识适用日期', { exact: true }).fill('2026-02-01');
  await page.getByRole('button', { name: '检查所选日期适用性' }).click();
  await expect(page.getByText('数据操作无法完成：METRIC_NOT_APPLICABLE')).toBeVisible();
  await expect(page.getByRole('region', { name: '指标口径概览' })).toBeVisible();
  await page.getByRole('tab', { name: 'Wiki', exact: true }).click();
  await page.getByRole('tab', { name: '关系图', exact: true }).click();
  await page.getByRole('button', { name: '关系节点：合成验收指标', exact: true }).click();
  await page.getByRole('button', { name: '查看这个指标怎么算', exact: true }).click();
  await expect(page.getByRole('region', { name: '指标口径概览' }).getByRole('heading', { name: '合成验收指标' })).toBeVisible();
  await expect(page.getByLabel('指标分子', { exact: true })).not.toBeVisible();
  await page.screenshot({ path: '../.cache/screenshots/knowledge-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '../.cache/screenshots/knowledge-mobile.png', fullPage: true });
  const jobs = await (await request.get('http://127.0.0.1:8001/api/v1/jobs')).json();
  expect(jobs.items.every((j: { kind: string }) => j.kind === 'document')).toBe(true);
});
