import { expect, test } from '@playwright/test';

test('document library, referenced Wiki, circular graph and reviewed rules work in the unified workspace', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const source = '# ArrDelay\n\nArrDelay is arrival time deviation. Early arrivals show negative numbers.\n\n| Field | Meaning |\n| --- | --- |\n| ArrDelay | Keep negative values for early arrivals |\n\n# Cancelled\n\nCancelled is a flight cancellation indicator.\n';
  const suffix = String(Date.now());
  const title = `合成浏览器验收材料-${suffix}`;
  const ruleTitle = `合成验收规则-${suffix}`;
  await page.goto('/knowledge');
  await expect(page.getByRole('heading', { name: '让知识，成为分析的起点。' })).toBeVisible();
  await expect(page.getByRole('tab', { name: '文档管理', exact: true })).toBeVisible();
  await expect(page.getByRole('tab', { name: /处理任务|指标定义/ })).toHaveCount(0);
  await expect(page.getByText('查阅固定版本的知识', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '＋ 新建文档', exact: true }).click();
  await page.getByLabel('原文文件', { exact: true }).setInputFiles({ name: 'synthetic-knowledge.md', mimeType: 'text/markdown', buffer: Buffer.from(source) });
  await page.getByLabel('文档标题', { exact: true }).fill(title);
  await page.getByRole('button', { name: '保存文档', exact: true }).click();
  const card = page.getByRole('article', { name: title, exact: true });
  await expect(card.getByText('完成', { exact: true })).toBeVisible();
  await card.getByRole('button').first().click();
  const document = page.getByRole('dialog', { name: '文档原文', exact: true });
  await expect(document.getByRole('combobox', { name: '原文历史版本', exact: true })).toBeVisible();
  await expect(document.getByRole('cell', { name: 'Keep negative values for early arrivals', exact: true })).toBeVisible();
  await document.getByRole('tab', { name: '可引用片段', exact: true }).click();
  await document.getByRole('button', { name: '选作 Wiki 引用', exact: true }).first().click();
  await page.keyboard.press('Escape');
  await expect(document).toBeHidden();

  await page.getByRole('tab', { name: 'Wiki', exact: true }).click();
  await page.getByRole('button', { name: '新建 Wiki', exact: true }).click();
  await page.getByLabel('Wiki 页面标识', { exact: true }).fill(`browser-arrivals-${suffix}`);
  await page.getByLabel('Wiki 标题', { exact: true }).fill('提前到达的解释');
  await page.getByRole('button', { name: /插入所选原文及引用/ }).click();
  await page.getByRole('button', { name: '保存人工草稿', exact: true }).click();
  await expect(page.getByText('已保存为新草稿版本', { exact: true })).toBeVisible();
  await expect(page.getByRole('group', { name: '知识引用关系图', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '阅读解释', exact: true }).click();
  await expect(page.getByRole('button', { name: '查看引用 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '审核并发布', exact: true }).click();
  await page.getByRole('button', { name: '确认发布', exact: true }).click();
  await expect(page.getByText('已发布新版本', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '版本历史与回滚', exact: true }).click();
  const history = page.getByRole('dialog').filter({ hasText: 'Wiki 历史' });
  await expect(history.getByText('v2 · 已发布', { exact: true })).toBeVisible();
  await history.getByRole('button', { name: '以此版本新建草稿' }).last().click();
  await expect(page.getByText('已从历史创建新的回滚草稿，尚未发布')).toBeVisible();

  await page.getByRole('tab', { name: '文档管理', exact: true }).click();
  await page.getByRole('button', { name: '新建规则说明', exact: true }).click();
  const rule = page.getByRole('dialog', { name: '计算规则说明', exact: true });
  await rule.getByLabel('规则标识', { exact: true }).fill(`browser_test_rate_${suffix}`);
  await rule.getByLabel('规则名称', { exact: true }).fill(ruleTitle);
  await rule.getByLabel('规则分组', { exact: true }).fill('carrier_id');
  await rule.getByLabel('规则分子', { exact: true }).fill('合成符合条件记录数 × 100');
  await rule.getByLabel('规则分母', { exact: true }).fill('合成全部记录数');
  await rule.getByLabel('规则过滤', { exact: true }).fill('cancelled=0');
  await rule.getByLabel('规则所需字段', { exact: true }).fill('cancelled');
  await rule.getByLabel('规则空值处理', { exact: true }).fill('零分母返回 null');
  await rule.getByRole('combobox', { name: '规则参考文档', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').getByText(`${title} v1`, { exact: true }).click();
  await rule.getByRole('button', { name: '保存规则草稿' }).click();
  await expect(page.getByText('规则已保存为待审核新版本')).toBeVisible();
  const drafts = await (await request.get('http://127.0.0.1:8001/api/v1/metrics')).json();
  const saved = drafts.items.find((item: { key: string }) => item.key === `browser_test_rate_${suffix}`);
  expect(saved.approved_revision_id).toBeNull();
  await rule.getByRole('button', { name: '审核此规则' }).click();
  await page.getByRole('button', { name: '确认审核', exact: true }).click();
  await expect(page.getByText('规则审核完成，将供新调查使用')).toBeVisible();
  const fixed = await (await request.post('http://127.0.0.1:8001/api/v1/knowledge/snapshots')).json();
  const accepted = await request.get(`http://127.0.0.1:8001/api/v1/metrics/browser_test_rate_${suffix}/resolve?snapshot_id=${fixed.id}&as_of=2026-01-15`);
  expect(accepted.ok()).toBe(true);
  const rejected = await request.get(`http://127.0.0.1:8001/api/v1/metrics/browser_test_rate_${suffix}/resolve?snapshot_id=${fixed.id}&as_of=2026-02-01`);
  expect(rejected.ok()).toBe(false);
  expect((await rejected.json()).error.code).toBe('METRIC_NOT_APPLICABLE');
  await rule.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(rule).toBeHidden();
  await expect(page.getByRole('article', { name: ruleTitle, exact: true })).toBeVisible();

  await page.getByRole('tab', { name: 'Wiki', exact: true }).click();
  await page.getByRole('tab', { name: '关系图', exact: true }).click();
  const node = page.getByRole('button', { name: `关系节点：${ruleTitle}`, exact: true });
  await expect(node.locator('circle')).toHaveAttribute('r', '46');
  await node.hover();
  await expect.poll(() => node.locator('.graph-node-shape').evaluate(element => getComputedStyle(element).transform)).not.toBe('none');
  await node.click();
  await expect(page.locator('.graph-node-detail')).toContainText(ruleTitle);
  await page.locator('.route-library').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: '../.cache/screenshots/knowledge-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '查看规则文档 ↗', exact: true }).click();
  await expect(rule.getByRole('region', { name: '指标口径概览' }).getByRole('heading', { name: ruleTitle })).toBeVisible();
  await expect(rule.getByLabel('规则分子', { exact: true })).not.toBeVisible();
  await rule.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(rule).toBeHidden();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.route-library').evaluate(element => { element.scrollTop = 0; });
  await expect.poll(() => page.locator('.workspace-sidebar').evaluate(element => element.getBoundingClientRect().right <= 1)).toBe(true);
  await expect.poll(() => page.locator('.knowledge-graph-canvas').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  expect(await page.evaluate(() => window.document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../.cache/screenshots/knowledge-mobile.png', fullPage: true });
  await page.locator('.knowledge-graph').screenshot({ path: '../.cache/screenshots/knowledge-graph-mobile.png' });
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await expect(page.getByRole('navigation', { name: '主导航' })).toBeInViewport();
  await page.getByRole('button', { name: '关闭导航', exact: true }).click();
  expect(errors).toEqual([]);
});

test('a document can be written directly without uploading a file', async ({ page }) => {
  await page.goto('/knowledge');
  await page.getByRole('button', { name: '＋ 新建文档', exact: true }).click();
  const title = `直接撰写的参考说明-${Date.now()}`;
  await page.getByLabel('文档标题', { exact: true }).fill(title);
  await page.getByLabel('文档内容', { exact: true }).fill('# 合成范围说明\n\n这是合成测试说明，保留提前到达的负值。');
  await page.getByRole('button', { name: '保存文档', exact: true }).click();
  const card = page.getByRole('article', { name: title, exact: true });
  await expect(card.getByText('完成', { exact: true })).toBeVisible();
  await page.screenshot({ path: '../.cache/screenshots/document-library-desktop.png' });
  await card.getByRole('button').first().click();
  await expect(page.getByRole('dialog', { name: '文档原文', exact: true })).toContainText('保留提前到达的负值');
});
